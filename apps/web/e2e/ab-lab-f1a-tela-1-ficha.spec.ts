test('ficha carregando: esqueleto "Carregando a ficha…" enquanto o servidor não responde', async ({ page, context }, info) => {
  const a = await preparar(page, context, info)
  await abrirLista(page); await semAnimacao(page)
  const trava = await conectar()
  try {
    await trava.query('begin')
    await trava.query('lock table public.ab_native_fichas in access exclusive mode')
    await linha(page, a.m, 'r66').getByRole('button', { name: 'Testar no YouTube' }).click()
    const f = page.locator('[aria-busy="true"]', { hasText: F.carregandoMeta }).first()
    await expect(page.getByText(F.carregandoMeta)).toBeVisible({ timeout: 15_000 })
    // F-5: o mockup `ficha-carregando` mostra a frase de estado e o apoio; a tela mostra só "Carregando a ficha…"
    await expect.soft(f, 'F-5: a ficha carregando traz a frase do mockup').toContainText(estreito(info) ? F.carregandoEstreita.frase : F.carregando.frase)
    await foto(page, info, 'ficha-carregando')
    await medirEAfirmar(page, page.getByRole('region', { name: 'Vídeos do A/B Lab' }), 'ficha-carregando', info, a.coleta)
  } finally {
    await trava.query('rollback').catch(() => undefined)
    await trava.end()
  }
  await expect(page.getByText(F.carregandoMeta)).toHaveCount(0, { timeout: 30_000 })
})

