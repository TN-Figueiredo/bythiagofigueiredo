// P4a-E3 e P4a-E4: envio do "Encerrar" (duplo clique, espera longa, sem resposta) e a faixa lendo o banco depois de recarregar.
import { test, expect } from '@playwright/test'
import { ctl, estadoFalso, horaSpManual, lerTeste, limpar } from './ab-lab-p4a-suporte/semente'
import { AUTH, abrir, botaoEncerrar, dialogoEncerrar, esperarLimpo, foto, nomeDaFoto, preparar, temaDoProjeto } from './ab-lab-p4a-suporte/comum'

test.use({ storageState: AUTH.admin })
test.beforeAll(async () => { await limpar() })

test('E3a: duplo clique em "Encerrar e ficar com B" gera UMA requisição de ação e UM par de escritas no YouTube', async ({ page, context, baseURL }, info) => {
  const tema = temaDoProjeto(info)
  const { t, coleta, postsDeAcao } = await preparar(page, context, baseURL!, tema, { nome: `E3a ${info.project.name}`, status: 'active' })
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 3000 }) // segura a escrita para o 2º clique cair em "Encerrando…"
  await abrir(page, t.url)
  await botaoEncerrar(page).click()
  const dlg = dialogoEncerrar(page)
  await dlg.getByRole('radio', { name: 'Variante B' }).check()
  const antes = postsDeAcao()
  await dlg.getByRole('button', { name: 'Encerrar e ficar com B' }).dblclick()
  await expect(dlg.getByRole('button', { name: 'Encerrando…' })).toBeVisible()
  await expect(dlg.getByText('Pode levar até 1 minuto.', { exact: false })).toBeVisible()
  await foto(page, nomeDaFoto('E3', 'encerrando', info, tema))
  await expect(dlg).toHaveCount(0, { timeout: 30_000 })
  expect(postsDeAcao() - antes, 'requisições de ação de servidor').toBe(1)
  await expect.poll(async () => (await lerTeste(t.testId)).status, { timeout: 15_000 }).toBe('completed')
  const yt = await estadoFalso()
  expect(yt.escritas, 'escritas no YouTube').toEqual(['videos.update', 'thumbnails.set'])
  const db = await lerTeste(t.testId)
  expect(db.restore_seq).toBe(1)
  expect(db.restore_status?.title?.estado).toBe('ok')
  expect(db.restore_status?.thumbnail?.estado).toBe('ok')
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 0 })
  esperarLimpo(coleta, 'E3a')
})

test('E3b: enquanto "Encerrando…" o X e o Esc estão livres; passados 45 s sem resposta o diálogo diz "Sem resposta" e NÃO oferece repetir "Encerrar"', async ({ page, context, baseURL }, info) => {
  const tema = temaDoProjeto(info)
  await page.clock.install()
  const { t, coleta } = await preparar(page, context, baseURL!, tema, { nome: `E3b ${info.project.name}`, status: 'active' })
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 8000 })
  await abrir(page, t.url)
  await botaoEncerrar(page).click()
  const dlg = dialogoEncerrar(page)
  await dlg.getByRole('radio', { name: 'Variante B' }).check()
  await dlg.getByRole('button', { name: 'Encerrar e ficar com B' }).click()
  await expect(dlg.getByRole('button', { name: 'Encerrando…' })).toBeVisible()
  // o X está livre durante o envio
  await expect(dlg.getByRole('button', { name: 'Fechar' })).toBeEnabled()
  // 46 s depois (relógio da página) sem resposta
  await page.clock.fastForward(46_000)
  await expect(dlg.getByText('Sem resposta')).toBeVisible()
  await expect(dlg.getByText('Não sabemos se o encerramento foi feito. Recarregue a página para ver o resultado.')).toBeVisible()
  await expect(dlg.getByRole('button', { name: /^Encerrar/ })).toHaveCount(0)
  await expect(dlg.getByRole('button', { name: 'Recarregar' })).toBeVisible()
  await foto(page, nomeDaFoto('E3', 'sem-resposta', info, tema))
  // a escrita do servidor terminou depois, uma vez só
  await expect.poll(async () => (await lerTeste(t.testId)).status, { timeout: 30_000 }).toBe('completed')
  await expect.poll(async () => (await estadoFalso()).escritas, { timeout: 30_000 }).toEqual(['videos.update', 'thumbnails.set'])
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 0 })
  esperarLimpo(coleta, 'E3b')
})

test('E3c: conexão caída ao confirmar: "Sem resposta", nada escrito no YouTube nem no banco, sem botão de repetir "Encerrar"', async ({ page, context, baseURL }, info) => {
  const tema = temaDoProjeto(info)
  const { t } = await preparar(page, context, baseURL!, tema, { nome: `E3c ${info.project.name}`, status: 'active' })
  await abrir(page, t.url)
  await botaoEncerrar(page).click()
  const dlg = dialogoEncerrar(page)
  await dlg.getByRole('radio', { name: 'Variante B' }).check()
  await context.setOffline(true)
  await dlg.getByRole('button', { name: 'Encerrar e ficar com B' }).click()
  await expect(dlg.getByText('Sem resposta')).toBeVisible({ timeout: 20_000 })
  await expect(dlg.getByRole('button', { name: /^Encerrar/ })).toHaveCount(0)
  await context.setOffline(false)
  const db = await lerTeste(t.testId)
  expect(db.status).toBe('active')
  expect(db.restore_seq).toBe(0)
  expect((await estadoFalso()).escritas).toEqual([])
})

test('E4: fechar o diálogo durante "Encerrando…" e recarregar: a faixa lê em_andamento do banco ("Trocando pela variante B…", "desde [hora SP]"), sem diálogo reaberto', async ({ page, context, baseURL }, info) => {
  const tema = temaDoProjeto(info)
  const { t, coleta } = await preparar(page, context, baseURL!, tema, { nome: `E4 ${info.project.name}`, status: 'active' })
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 9000 })
  await abrir(page, t.url)
  await botaoEncerrar(page).click()
  const dlg = dialogoEncerrar(page)
  await dlg.getByRole('radio', { name: 'Variante B' }).check()
  await dlg.getByRole('button', { name: 'Encerrar e ficar com B' }).click()
  await expect(dlg.getByRole('button', { name: 'Encerrando…' })).toBeVisible()
  await dlg.getByRole('button', { name: 'Fechar' }).click()
  await expect(dlg).toHaveCount(0)
  // o claim já gravou em_andamento (a escrita lenta segura o resto)
  await expect.poll(async () => (await lerTeste(t.testId)).restore_status?.title?.estado, { timeout: 10_000 }).toBe('em_andamento')
  const emDb = (await lerTeste(t.testId)).restore_status!.title!.em
  await page.reload()
  await page.waitForLoadState('networkidle')
  const faixa = page.getByRole('region', { name: 'Restauração do vídeo' })
  await expect(faixa).toBeVisible()
  await expect(faixa).toContainText('Trocando pela variante B…')
  await expect(faixa).toContainText(`Trocando desde ${horaSpManual(new Date(emDb))}.`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await foto(page, nomeDaFoto('E4', 'faixa-em-andamento-apos-recarregar', info, tema))
  await expect.poll(async () => (await lerTeste(t.testId)).restore_status?.title?.estado, { timeout: 30_000 }).toBe('ok')
  await ctl({ op: 'atrasar', chamada: 'thumbnails.set', ms: 0 })
  esperarLimpo(coleta, 'E4')
})
