test('S7: "Não é teste" pede o 2º toque, grava o descarte e o "Retomar" do nosso teste é aceito', async ({ page, context }, info) => {
  test.skip(!soNoProjeto(info), 'fluxo com escrita: um projeto basta')
  const a = await preparar(page, context, info)
  const dh = 'f0f0f0f0f0f0f0f0'
  await ytCtl({ op: 'reset', titulo: T.lv, thumbDhash: dh, blobs: { [BLOB('nosso-A')]: dh, [BLOB('nosso-B')]: dh, [BLOB('nosso-C')]: dh } })
  await abrirLista(page); await semAnimacao(page)
  await linha(page, a.m, 'lv').getByRole('button', { name: 'Ver teste' }).click()
  await cartao(page).getByRole('button', { name: S.naoETeste }).click()
  await expect(cartao(page)).toContainText(S.liberarDecisao)
  await expect(cartao(page)).toContainText(S.liberarConsequencia)
  await foto(page, info, 's7-liberar-confirma')
  await medirEAfirmar(page, cartao(page), 's7-liberar-confirma', info, a.coleta, { maxPri: 2 })
  const antes = await consultar<{ estado: string }>('select estado from ab_native_tests where video_id=$1', [a.m.v.lv!.id])
  expect(antes[0]!.estado, 'o 1º toque não grava').toBe('em_andamento')
  await cartao(page).getByRole('button', { name: S.liberar }).click()
  await expect.poll(async () => (await consultar<{ estado: string }>('select estado from ab_native_tests where video_id=$1', [a.m.v.lv!.id]))[0]?.estado, { timeout: 20_000 }).toBe('descartado')
  // "Retomar" do nosso teste (página do teste): aceito agora que não há registro aberto
  await page.goto(`/cms/youtube/ab-lab/${a.m.testes.lv!.testId}`)
  const retomar = page.getByRole('button', { name: /^Retomar/ }).first()
  await expect(retomar).toBeVisible({ timeout: 30_000 })
  await retomar.click()
  await expect.poll(async () => (await consultar<{ status: string }>('select status from ab_tests where id=$1', [a.m.testes.lv!.testId]))[0]?.status, { timeout: 30_000 }).toBe('active')
})

test.describe('dia 14 com duas versões', () => {
  test('"Responder" abre a pergunta sem primário; a vizinha não pula mais que o bloco; "B venceu" grava venceu_nova', async ({ page, context }, info) => {
    const a = await preparar(page, context, info)
    await abrirLista(page); await semAnimacao(page)
    const li = linha(page, a.m, 'sm')
    await expect(li).toHaveAttribute('data-estado', 'resultado_pronto')
    const botao = li.getByRole('button', { name: D.responder })
    const proxima = li.locator('xpath=following-sibling::li[1]')
    const y0 = (await proxima.boundingBox())?.y ?? 0
    await botao.click()
    await expect(li).toContainText(D.pergunta)
    await expect(li).toContainText(D.apoio(new Date(a.m.agora.getTime() - 14 * 86_400_000 - 3_600_000)))
    for (const t of [D.originalFicou, D.novaVenceu, D.ficouIgual, D.inconclusivo, D.naoVi]) await expect(li.getByRole('button', { name: new RegExp(t.replace(/[()]/g, '\\$&')) })).toBeVisible()
    await expect(li).toContainText(D.avisoMudar)
    expect(await li.locator('.pri:visible').count(), 'a pergunta não tem primário').toBe(0)
    const y1 = (await proxima.boundingBox())?.y ?? 0
    const bloco = (await li.locator('.cn-d14, [class*=d14], [data-resposta]').first().evaluate((e) => (e.closest('.cn-vrow, li') as HTMLElement).getBoundingClientRect().height).catch(() => 0))
    test.info().annotations.push({ type: 'salto', description: `a vizinha desceu ${(y1 - y0).toFixed(1)} px; linha aberta ${bloco.toFixed(1)} px` })
    expect(y1 - y0, 'a vizinha desce, e não mais que a altura da linha aberta').toBeLessThanOrEqual(bloco + 2)
    await foto(page, info, 'd14-duas')
    await medirEAfirmar(page, page.getByRole('region', { name: 'Vídeos do A/B Lab' }), 'd14-duas', info, a.coleta, { maxPri: 2 })
    if (!soNoProjeto(info)) return
    await li.locator('[data-resposta="venceu_nova"]').click()
    await expect(li).toHaveAttribute('data-estado', 'ficou_no_ar', { timeout: 20_000 })
    await expect(li).toContainText(D.seloNova)
    const r = await consultar<{ resposta_dono: string; variante_vencedora: number | null; estado: string; vencedor_fonte: string | null }>(
      'select resposta_dono, variante_vencedora, estado, vencedor_fonte from ab_native_tests where video_id=$1', [a.m.v.sm!.id])
    expect(r).toHaveLength(1)
    expect(r[0]!.resposta_dono).toBe('venceu_nova')
    expect(r[0]!.variante_vencedora).toBe(2)
    expect(await contarFichas(a.m.v.sm!.id), 'sem ficha nova').toBe(await contarFichas(a.m.v.sm!.id))
    await expect(li).not.toContainText('Mudar minha resposta')
  })

  test('sem resposta (prazo passado): "A (original) ficou" grava venceu_original; "Ficou igual" grava sem vencedor', async ({ page, context }, info) => {
    test.skip(!soNoProjeto(info), 'fluxo com escrita: um projeto basta')
    const a = await preparar(page, context, info)
    await abrirLista(page); await semAnimacao(page)
    const li = linha(page, a.m, 'sp')
    await li.getByRole('button', { name: D.responder }).click()
    await li.locator('[data-resposta="venceu_original"]').click()
    await expect(li).toHaveAttribute('data-estado', 'ficou_no_ar', { timeout: 20_000 })
    await expect(li).toContainText(D.seloOriginal)
    const r = await consultar<{ resposta_dono: string; variante_vencedora: number | null }>('select resposta_dono, variante_vencedora from ab_native_tests where video_id=$1', [a.m.v.sp!.id])
    expect(r[0]!.resposta_dono).toBe('venceu_original')
    expect(r[0]!.variante_vencedora).toBe(1)
    // e o "ficou igual" no outro (sm)
    const sm = linha(page, a.m, 'sm')
    await sm.getByRole('button', { name: D.responder }).click()
    await sm.locator('[data-resposta="ficou_igual"]').click()
    await expect(sm).toHaveAttribute('data-estado', 'respondido_sem_vencedor', { timeout: 20_000 })
    await expect(sm).toContainText(D.seloSemVencedor.ficou_igual)
    await expect(sm).not.toContainText('Ficou no ar')
    const r2 = await consultar<{ resposta_dono: string; variante_vencedora: number | null }>('select resposta_dono, variante_vencedora from ab_native_tests where video_id=$1', [a.m.v.sm!.id])
    expect(r2[0]!.resposta_dono).toBe('ficou_igual')
    expect(r2[0]!.variante_vencedora, 'sem vencedor').toBeNull()
  })

  test('sem conexão ao responder: "Sem conexão. Nada foi registrado." e nada gravado; "Tentar de novo" grava', async ({ page, context }, info) => {
    test.skip(!soNoProjeto(info), 'fluxo com escrita: um projeto basta')
    const a = await preparar(page, context, info, { naoEsperadas: [/ERR_INTERNET_DISCONNECTED/] })
    await abrirLista(page); await semAnimacao(page)
    const li = linha(page, a.m, 'sm')
    await li.getByRole('button', { name: D.responder }).click()
    await context.setOffline(true)
    await li.locator('[data-resposta="venceu_nova"]').click()
    await expect(li).toContainText(D.semConexao, { timeout: 20_000 })
    expect(await consultar('select 1 from ab_native_tests where video_id=$1 and resposta_dono is not null', [a.m.v.sm!.id])).toHaveLength(0)
    await foto(page, info, 'd14-sem-conexao')
    await context.setOffline(false)
    await li.getByRole('button', { name: D.tentarDeNovo }).click()
    await expect(li).toHaveAttribute('data-estado', 'ficou_no_ar', { timeout: 20_000 })
  })
})

