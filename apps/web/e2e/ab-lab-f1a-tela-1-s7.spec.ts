  await expect(c).toContainText(/Visto de fora desde \d\d\/\d\d às \d\d:\d\d\. Última leitura .+\. Você ainda não confirmou\./)
  await expect(c).toContainText(S.tituloDeAntes)
  await expect(c).toContainText(S.tituloNovo)
  await expect(c).toContainText('3 de 5')
  await expect(c).toContainText(S.dica)
  await expect(c.getByRole('button', { name: S.confirmar })).toBeVisible()
  await expect(c.getByRole('button', { name: S.naoETeste })).toBeVisible()
  expect(await page.evaluate(() => document.activeElement?.tagName), 'foco no h2 do cartão').toBe('H2')
  await foto(page, info, 's7-detectado')
  await medirEAfirmar(page, c, 's7-detectado', info, a.coleta, { maxPri: 2 })
  await page.keyboard.press('Escape')
